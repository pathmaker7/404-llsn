// Builds app/data/sites.js: preset candidate points derived from the DEM, not typed in by hand.
// Feature centres come from the USGS Gazetteer of Planetary Nomenclature (via the Wikipedia infoboxes
// that cite it). A "rim" preset is the highest DEM point on the ring 0.85 to 1.15 crater radii from
// the centre, where a lander would chase sunlight; a "summit" is the highest point within `size` km.
// Crater-floor presets show permanently shadowed ground.
// Run after build-dem: node tools/build-sites.cjs
const fs = require('fs');
const path = require('path');
const Terrain = require('../app/terrain.js');
const DEM = require('../app/data/dem.js');

const Sky = require('../app/sky.js');
const Analysis = require('../app/analysis.js');

const T = Terrain(DEM);
const MAST_M = 2;
const BODIES = Analysis.makeTimes(new Date('2026-11-14T00:00:00Z'), 365, 12).map(Sky.bodiesMoonFixed);
const FEATURES = [
  // name, gazetteer centre lat, lon (deg E), crater diameter km (or search radius for a summit), kind
  ['Shackleton rim', -89.67, 129.78, 21.0, 'rim'],
  ['de Gerlache rim', -88.5, -87.1, 32.4, 'rim'],
  ['Slater rim', -88.08, 111.29, 25.12, 'rim'],
  ['Shoemaker rim', -88.1, 44.9, 50.9, 'rim'],
  ['Faustini rim', -87.3, 77.0, 42.48, 'rim'],
  ['Haworth rim (Malapert massif side)', -86.9, -4.0, 51.4, 'rim'],
  ['Malapert rim', -84.9, 12.9, 69, 'rim'],
  ['Nobile rim', -85.28, 53.27, 79.27, 'rim'],
  ['Mons Mouton (best-lit point)', -84.6, 31.0, 12, 'summit'],
  ['Shackleton floor (shadowed)', -89.67, 129.78, 0, 'floor'],
  ['Faustini floor (shadowed)', -87.3, 77.0, 0, 'floor'],
];

const kmPerPx = DEM.scale / 1000;
const sites = FEATURES.map(([name, lat, lon, size, kind]) => {
  const v = T.latLonToVec(lat, lon);
  const [ci, cj] = T.vecToGrid(v[0], v[1], v[2]);
  let best = { i: ci, j: cj, h: T.heightAtGrid(ci, cj) };
  const [rMin, rMax] = kind === 'rim' ? [0.85 * size / 2, 1.15 * size / 2] : [0, size];
  if (kind === 'floor') {
    // The gazetteer centre can sit on the side of a pit in the floor; take the lowest point within 2 km.
    const r = Math.ceil(2 / kmPerPx);
    for (let dj = -r; dj <= r; dj++)
      for (let di = -r; di <= r; di++) {
        const i = Math.round(ci) + di, j = Math.round(cj) + dj, h = T.heightAtGrid(i, j);
        if (Math.hypot(i - ci, j - cj) * kmPerPx <= 2 && h < best.h) best = { i, j, h };
      }
  } else {
    // Every candidate pixel gets its real horizon and a year of sunlight; the best-lit one wins.
    best = { sun: -1 };
    const r = Math.ceil(rMax / kmPerPx);
    for (let dj = -r; dj <= r; dj++)
      for (let di = -r; di <= r; di++) {
        const i = Math.round(ci) + di, j = Math.round(cj) + dj, dKm = Math.hypot(i - ci, j - cj) * kmPerPx;
        if (dKm < rMin || dKm > rMax) continue;
        const ll = T.gridToLatLon(i, j), h = T.heightAtGrid(i, j);
        const site = { lat: ll.lat, lon: ll.lon, heightM: h, horizon: T.horizon(ll.lat, ll.lon, MAST_M) };
        const tr = Analysis.track(site, BODIES, T.horizonAt, 0.5);
        const sun = tr.cumSun[BODIES.length] / BODIES.length;
        if (sun > best.sun) best = { i, j, h, sun };
      }
  }
  const ll = T.gridToLatLon(best.i, best.j);
  const feature = name.replace(/ (rim|floor|\().*$/, '');
  const how = { floor: 'lowest DEM point within 2 km of the centre of', rim: 'best-lit DEM point (1 year, 2 m mast) on the rim ring of', summit: `best-lit DEM point (1 year, 2 m mast) within ${size} km of` }[kind];
  return {
    name, kind,
    lat: +ll.lat.toFixed(4), lon: +ll.lon.toFixed(4), heightM: Math.round(best.h),
    from: `${how} ${feature} (USGS gazetteer centre ${lat}, ${lon})`,
  };
});

const dest = path.join(__dirname, '..', 'app', 'data', 'sites.js');
fs.writeFileSync(dest, `// Generated by tools/build-sites.cjs (do not edit).
var PRESET_SITES = ${JSON.stringify(sites, null, 2)};
if (typeof module !== 'undefined') module.exports = PRESET_SITES;
`);
for (const s of sites) console.log(`${s.name.padEnd(30)} ${s.lat.toFixed(3).padStart(8)} ${s.lon.toFixed(3).padStart(9)} ${String(s.heightM).padStart(6)} m`);
