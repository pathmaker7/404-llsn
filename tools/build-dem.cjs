// Builds app/data/dem.js from the NASA LRO LOLA south polar DEM (LDEM_75S_240M.IMG).
// Source: https://pds-geosciences.wustl.edu/lro/lro-l-lola-3-rdr-v1/lrolol_1xxx/data/lola_gdr/polar/img/
// Input: 3812 x 3812 int16 LSB, 240 m/px, height = DN * 0.5 m above a 1737.4 km sphere.
// Output: 2x2 averaged (480 m/px), cropped to about 80 S, whole metres as int16, base64.
// Run: node tools/build-dem.cjs <path/to/ldem_75s_240m.img>
const fs = require('fs');
const path = require('path');

const N_IN = 3812, SCALE_IN = 240, FACTOR = 2;
const R_MOON_M = 1737400;
const LAT_EDGE = -80;

const file = process.argv[2];
if (!file) throw new Error('usage: node tools/build-dem.cjs <ldem_75s_240m.img>');
const buf = fs.readFileSync(file);
if (buf.length !== N_IN * N_IN * 2) throw new Error(`expected ${N_IN * N_IN * 2} bytes, got ${buf.length}`);

const scale = SCALE_IN * FACTOR;
const halfM = 2 * R_MOON_M * Math.tan(((90 + LAT_EDGE) * Math.PI) / 360); // stereographic radius of the crop edge
const n = 2 * Math.ceil(halfM / scale);
// The input centre lies between pixels (N/2 + 0.5, 1-based), so output pixel k covers input pixels around it.
const offIn = N_IN / 2 - (n / 2) * FACTOR;
const out = new Int16Array(n * n);
for (let j = 0; j < n; j++) {
  for (let i = 0; i < n; i++) {
    let s = 0;
    for (let dj = 0; dj < FACTOR; dj++)
      for (let di = 0; di < FACTOR; di++)
        s += buf.readInt16LE(((offIn + j * FACTOR + dj) * N_IN + (offIn + i * FACTOR + di)) * 2);
    out[j * n + i] = Math.round((s / (FACTOR * FACTOR)) * 0.5);
  }
}
const b64 = Buffer.from(out.buffer).toString('base64');
const js = `// Generated by tools/build-dem.cjs from NASA LRO LOLA LDEM_75S_240M (do not edit).
// Polar stereographic, south pole at the grid centre, longitude 0 up, 90 E right.
var DEM = { n: ${n}, scale: ${scale}, radius: ${R_MOON_M}, source: "NASA LRO LOLA LDEM_75S_240M, 2x2 averaged", data: "${b64}" };
if (typeof module !== 'undefined') module.exports = DEM;
`;
const dest = path.join(__dirname, '..', 'app', 'data', 'dem.js');
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, js);
console.log(`wrote ${dest}: ${n}x${n} at ${scale} m/px, ${(js.length / 1e6).toFixed(1)} MB`);
