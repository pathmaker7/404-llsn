// Writes docs/translations-review.md: every interface string in English, Russian and Kyrgyz side by side,
// for a native speaker to proofread. After review, set REVIEWED.<lang> = true in app/i18n.js.
// Run: npm run i18n:review
const fs = require('fs');
const path = require('path');
const I = require('../app/i18n.js');

const cell = (s) => s.replace(/<\/?b>/g, '**').replace(/\|/g, '\\|');
const rows = Object.keys(I.S.en).map((k) => `| ${k} | ${cell(I.S.en[k])} | ${cell(I.S.ru[k])} | ${cell(I.S.ky[k])} |`);
const md = `# Interface translations for review

Generated by \`npm run i18n:review\` from app/i18n.js; do not edit here, edit app/i18n.js and regenerate.

Status: Russian reviewed: **${I.REVIEWED.ru ? 'yes' : 'no'}**. Kyrgyz reviewed: **${I.REVIEWED.ky ? 'yes' : 'no'}**. Until a native speaker signs off, the app labels the language "draft".

How to review: read each row; fix wording in app/i18n.js (keep every {placeholder} exactly as it is, \`npm test\` checks them), then set \`REVIEWED.ru\` / \`REVIEWED.ky\` to true. Screenshots: docs/screenshots/app-ru.png and app-ky.png (from \`npm run smoke\`).

| Key | English | Русский | Кыргызча |
|---|---|---|---|
${rows.join('\n')}
`;
fs.writeFileSync(path.join(__dirname, '..', 'docs', 'translations-review.md'), md);
console.log(`wrote docs/translations-review.md: ${rows.length} strings`);
